/** 词表匹配：返回第一个命中的情绪；没有则 undefined。 */
export function matchEmotion(text) {
  const s = String(text ?? '').toLowerCase()
  if (!s.trim()) return undefined
  let best
  let bestLen = 0
  for (const [emotion, words] of Object.entries(EMOTION_WORDS)) {
    for (const w of words) {
      const lw = w.toLowerCase()
      if (!lw) continue
      if (s.includes(lw) && lw.length > bestLen) {
        best = emotion
        bestLen = lw.length
      }
    }
  }
  return best
}

